-- IMPORTANTE:
-- El Python adjunto usa text-embedding-3-large reducido a 512 dimensiones.
-- Si cambias DOMORA_EMBED_DIMENSIONS, ajusta vector(512) aquí y recrea el índice.

create extension if not exists vector with schema extensions;

create table if not exists public.domora_rag_documents (
    id uuid primary key default gen_random_uuid(),
    relative_path text not null unique,
    sha256 text not null,
    community_id text not null,
    filename text not null,
    title text not null,
    doc_type text not null default '',
    status text not null default 'unknown',
    effective_date date null,
    page_count integer not null default 0,
    embedding_model text not null,
    embedding_dimensions integer not null default 512,
    indexed_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.domora_rag_chunks (
    id bigint generated by default as identity primary key,
    document_id uuid not null
        references public.domora_rag_documents(id)
        on delete cascade,
    community_id text not null,
    page integer not null,
    chunk_index integer not null,
    content text not null,
    embedding extensions.vector(512) not null,
    fts tsvector generated always as (
        to_tsvector('simple', coalesce(content, ''))
    ) stored,
    created_at timestamptz not null default now(),
    unique (document_id, page, chunk_index)
);

create index if not exists domora_rag_documents_community_idx
    on public.domora_rag_documents (community_id);

create index if not exists domora_rag_documents_status_idx
    on public.domora_rag_documents (status);

create index if not exists domora_rag_chunks_community_idx
    on public.domora_rag_chunks (community_id);

create index if not exists domora_rag_chunks_fts_idx
    on public.domora_rag_chunks
    using gin (fts);

-- HNSW recomendado para búsqueda vectorial.
create index if not exists domora_rag_chunks_embedding_hnsw_idx
    on public.domora_rag_chunks
    using hnsw (embedding extensions.vector_cosine_ops);

-- RLS: estas tablas no deben quedar directamente expuestas a propietarios.
alter table public.domora_rag_documents enable row level security;
alter table public.domora_rag_chunks enable row level security;

-- No creamos policies para anon/authenticated deliberadamente.
-- El backend usa service_role/secret key.
-- Si más adelante quieres acceso directo desde Supabase Auth, crea policies
-- basadas en una tabla de memberships, no en un community_id enviado por cliente.

create or replace function public.domora_hybrid_search(
    query_text text,
    query_embedding extensions.vector(512),
    target_community_id text,
    match_count integer default 18
)
returns table (
    chunk_id bigint,
    document_id uuid,
    community_id text,
    filename text,
    title text,
    doc_type text,
    status text,
    effective_date date,
    page integer,
    chunk_index integer,
    content text,
    semantic_similarity double precision,
    keyword_rank double precision,
    hybrid_score double precision
)
language sql
stable
security definer
set search_path = public, extensions
as $$
with eligible as (
    select
        c.id as chunk_id,
        c.document_id,
        c.community_id,
        c.page,
        c.chunk_index,
        c.content,
        c.embedding,
        c.fts,
        d.filename,
        d.title,
        d.doc_type,
        d.status,
        d.effective_date
    from public.domora_rag_chunks c
    join public.domora_rag_documents d
      on d.id = c.document_id
    where
        (
            c.community_id = 'global'
            or (
                target_community_id is not null
                and target_community_id <> 'global'
                and c.community_id = target_community_id
            )
        )
        and lower(coalesce(d.status, 'unknown')) not in (
            'superseded',
            'archived',
            'draft',
            'obsolete',
            'revoked',
            'repealed',
            'inactive'
        )
),
semantic_search as (
    select
        e.chunk_id,
        row_number() over (
            order by e.embedding <=> query_embedding
        ) as semantic_rank,
        (
            1.0 - (e.embedding <=> query_embedding)
        )::double precision as semantic_similarity
    from eligible e
    order by e.embedding <=> query_embedding
    limit greatest(match_count * 3, 30)
),
keyword_search as (
    select
        e.chunk_id,
        row_number() over (
            order by
                ts_rank_cd(
                    e.fts,
                    websearch_to_tsquery('simple', query_text)
                ) desc
        ) as keyword_position,
        ts_rank_cd(
            e.fts,
            websearch_to_tsquery('simple', query_text)
        )::double precision as keyword_rank
    from eligible e
    where
        query_text is not null
        and btrim(query_text) <> ''
        and e.fts @@ websearch_to_tsquery('simple', query_text)
    order by
        ts_rank_cd(
            e.fts,
            websearch_to_tsquery('simple', query_text)
        ) desc
    limit greatest(match_count * 3, 30)
),
combined_ids as (
    select chunk_id from semantic_search
    union
    select chunk_id from keyword_search
),
ranked as (
    select
        ids.chunk_id,
        coalesce(s.semantic_similarity, 0.0) as semantic_similarity,
        coalesce(k.keyword_rank, 0.0) as keyword_rank,
        (
            coalesce(
                1.0 / (60.0 + s.semantic_rank::double precision),
                0.0
            )
            +
            coalesce(
                1.0 / (60.0 + k.keyword_position::double precision),
                0.0
            )
        )::double precision as hybrid_score
    from combined_ids ids
    left join semantic_search s
      on s.chunk_id = ids.chunk_id
    left join keyword_search k
      on k.chunk_id = ids.chunk_id
)
select
    e.chunk_id,
    e.document_id,
    e.community_id,
    e.filename,
    e.title,
    e.doc_type,
    e.status,
    e.effective_date,
    e.page,
    e.chunk_index,
    e.content,
    r.semantic_similarity,
    r.keyword_rank,
    r.hybrid_score
from ranked r
join eligible e
  on e.chunk_id = r.chunk_id
order by
    r.hybrid_score desc,
    r.semantic_similarity desc
limit match_count;
$$;


-- Permisos explícitos para el backend con service_role.
grant select, insert, update, delete
on public.domora_rag_documents
to service_role;

grant select, insert, update, delete
on public.domora_rag_chunks
to service_role;

grant usage, select
on sequence public.domora_rag_chunks_id_seq
to service_role;

-- Evita que la función pueda ejecutarse directamente con las claves públicas.
revoke all on function public.domora_hybrid_search(
    text,
    extensions.vector,
    text,
    integer
) from public;

revoke all on function public.domora_hybrid_search(
    text,
    extensions.vector,
    text,
    integer
) from anon;

revoke all on function public.domora_hybrid_search(
    text,
    extensions.vector,
    text,
    integer
) from authenticated;

grant execute on function public.domora_hybrid_search(
    text,
    extensions.vector,
    text,
    integer
) to service_role;

-- Las tablas tampoco se conceden a anon/authenticated.
revoke all on public.domora_rag_documents from anon, authenticated;
revoke all on public.domora_rag_chunks from anon, authenticated;


-- ---------------------------------------------------------------------------
-- Historial de conversaciones del chat
-- ---------------------------------------------------------------------------

create table if not exists public.domora_rag_conversations (
    id uuid primary key default gen_random_uuid(),
    community_id text not null,
    user_id text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.domora_rag_messages (
    id bigint generated by default as identity primary key,
    conversation_id uuid not null
        references public.domora_rag_conversations(id)
        on delete cascade,
    role text not null check (role in ('user', 'assistant')),
    content text not null,
    citations jsonb null,
    created_at timestamptz not null default now()
);

create index if not exists domora_rag_conversations_owner_idx
    on public.domora_rag_conversations (user_id, community_id, updated_at desc);

create index if not exists domora_rag_messages_conversation_idx
    on public.domora_rag_messages (conversation_id, id);

alter table public.domora_rag_conversations enable row level security;
alter table public.domora_rag_messages enable row level security;

grant select, insert, update, delete
    on public.domora_rag_conversations to service_role;
grant select, insert, update, delete
    on public.domora_rag_messages to service_role;
grant usage, select
    on all sequences in schema public to service_role;

revoke all on public.domora_rag_conversations from anon, authenticated;
revoke all on public.domora_rag_messages from anon, authenticated;
