function definition(
  key: string,
  category: string,
  title: string,
  description: string,
  periodMode: ReportDefinition['periodMode'] = 'none',
  scopeMode: ReportDefinition['scopeMode'] = 'multiple',
  filters: ReportDefinition['filters'] = [],
  sensitivity: ReportSensitivity = 'financial',
): ReportDefinition {
  return {
    key,
    category,
    title,
    description,
    periodMode,
    scopeMode,
    filters,
    sensitivity,
    icon: REPORT_CATEGORIES.find((c) => c.key === category)!.icon,
    formats: ['pdf', 'xlsx'],
    status: 'available',
  };
}

